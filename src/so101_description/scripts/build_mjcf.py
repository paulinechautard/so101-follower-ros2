#!/usr/bin/env python3
"""
Make this repo's arm MJCF from LeRobot's, which stays untouched in mjcf/upstream/.

Changes:
- Fixed jaw: its mesh no longer collides, a box pad (fixed_jaw_pad) collides instead.
  MuJoCo collides a mesh as its convex hull, and the hull of wrist_roll_follower_so101_v1
  fills a wedge of the jaw gap that squeezes grasped objects out.
- --overlay FILE: adds the <asset> children of FILE to the model's assets and its
  <worldbody> bodies to the "gripper" body (the wrist camera).

Usage: build_mjcf.py INPUT OUTPUT [--model NAME] [--overlay FILE]
"""
import argparse
import sys
import xml.etree.ElementTree as ET

FIXED_JAW_MESH = 'wrist_roll_follower_so101_v1'
FIXED_JAW_PAD = {
    'name': 'fixed_jaw_pad', 'type': 'box', 'class': 'collision',
    'pos': '-0.0134 -0.000218 -0.0781', 'size': '0.0045 0.0075 0.025', 'rgba': '0.2 0.6 0.9 1',
}


def parse(path):
    return ET.parse(path, parser=ET.XMLParser(target=ET.TreeBuilder(insert_comments=True)))


def find_one(root, xpath, what):
    found = root.findall(xpath)
    if len(found) != 1:
        sys.exit(f'build_mjcf.py: expected one {what} ({xpath}), found {len(found)}')
    return found[0]


def patch_fixed_jaw(gripper):
    mesh = find_one(gripper, f"geom[@class='collision'][@mesh='{FIXED_JAW_MESH}']", 'fixed jaw collision mesh')
    mesh.set('contype', '0')
    mesh.set('conaffinity', '0')
    pad = ET.Element('geom', FIXED_JAW_PAD)
    pad.tail = mesh.tail
    gripper.insert(list(gripper).index(mesh) + 1, pad)


def add_overlay(root, gripper, path):
    overlay = parse(path).getroot()
    asset = find_one(root, 'asset', '<asset>')
    for child in overlay.findall('asset/*'):
        asset.append(child)
    # Before the moving jaw's body, after the gripper's own geoms and sites.
    index = next((i for i, c in enumerate(gripper) if c.tag == 'body'), len(gripper))
    for body in reversed(overlay.findall('worldbody/body')):
        gripper.insert(index, body)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('input')
    parser.add_argument('output')
    parser.add_argument('--model', help='model name (default: keep upstream)')
    parser.add_argument('--overlay')
    args = parser.parse_args()

    tree = parse(args.input)
    root = tree.getroot()
    gripper = find_one(root, ".//body[@name='gripper']", 'gripper body')
    patch_fixed_jaw(gripper)
    if args.overlay:
        add_overlay(root, gripper, args.overlay)
    if args.model:
        root.set('model', args.model)

    root.insert(0, ET.Comment(
        ' Generated by so101_description/scripts/build_mjcf.py from mjcf/upstream/so101_new_calib.xml.'
        ' Do not edit. '))
    root[0].tail = '\n  '
    ET.indent(tree, space='  ')
    tree.write(args.output, encoding='utf-8', xml_declaration=True)


if __name__ == '__main__':
    main()
